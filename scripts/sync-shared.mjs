#!/usr/bin/env node
// Copies the game code the app shares with the web game:
//   game/engine  <- hotel-clash-api/engine   (rules; the server runs the same files)
//   game/core    <- hotelclash/src/game       (GameStore: offline play + server sync, insights)
// Never edit the copies; change the source repo and run `npm run shared:sync`.
//
//   npm run shared:sync                 # defaults: ../../../node/hotel-clash-api, ../../hotelclash
//   ENGINE_SRC=... WEB_SRC=... npm run shared:sync
//   npm run shared:check                # fail if a copy is out of date (CI)
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const engineSrc = path.resolve(process.env.ENGINE_SRC || path.join(root, '..', '..', '..', 'node', 'hotel-clash-api', 'engine'));
const webSrc = path.resolve(process.env.WEB_SRC || path.join(root, '..', '..', 'hotelclash'));
const checkOnly = process.argv.includes('--check');
const CORE_FILES = ['gameStore.js', 'insights.js'];

for (const dir of [engineSrc, path.join(webSrc, 'src', 'game')]) {
  if (!existsSync(dir)) {
    console.error(`Not found: ${dir}. Set ENGINE_SRC / WEB_SRC.`);
    process.exit(1);
  }
}

const banner = (from) => `// GENERATED by scripts/sync-shared.mjs from ${from} — do not edit here.\n`;

// Engine: same hash algorithm as hotel-clash-api/src/engineInfo.js, so the app
// can tell when the server runs newer rules (GET /api/game/engine).
const engineFiles = readdirSync(engineSrc).filter((f) => f.endsWith('.js')).sort();
const hash = createHash('sha256');
for (const f of engineFiles) {
  hash.update(f);
  hash.update(readFileSync(path.join(engineSrc, f)));
}
const engineHash = hash.digest('hex').slice(0, 16);

const targets = [
  {
    dest: path.join(root, 'game', 'engine'),
    files: new Map([
      ...engineFiles.map((f) => [f, banner('hotel-clash-api/engine') + readFileSync(path.join(engineSrc, f), 'utf8')]),
      ['engine-hash.js', `${banner('hotel-clash-api/engine')}export const ENGINE_HASH = '${engineHash}';\n`],
    ]),
  },
  {
    dest: path.join(root, 'game', 'core'),
    files: new Map(CORE_FILES.map((f) => [f, banner('hotelclash/src/game') + readFileSync(path.join(webSrc, 'src', 'game', f), 'utf8')])),
  },
];

if (checkOnly) {
  const stale = targets.flatMap(({ dest, files }) =>
    [...files].filter(([f, content]) => !existsSync(path.join(dest, f)) || readFileSync(path.join(dest, f), 'utf8') !== content).map(([f]) => path.relative(root, path.join(dest, f)))
  );
  if (stale.length) {
    console.error(`Shared game code is out of date (${stale.join(', ')}). Run npm run shared:sync.`);
    process.exit(1);
  }
  console.log(`Shared game code is up to date (engine ${engineHash}).`);
} else {
  for (const { dest, files } of targets) {
    rmSync(dest, { recursive: true, force: true });
    mkdirSync(dest, { recursive: true });
    for (const [f, content] of files) writeFileSync(path.join(dest, f), content);
  }
  console.log(`Synced ${engineFiles.length} engine files (hash ${engineHash}) and ${CORE_FILES.length} core files.`);
}
